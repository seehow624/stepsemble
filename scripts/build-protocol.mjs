#!/usr/bin/env node
// Mechanically embed the canonical schema and identical validator for browsers.
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(await fs.readFile(path.join(root, "protocol/v1/schema.json"), "utf8"));
const source = (await fs.readFile(path.join(root, "protocol/validator.js"), "utf8")).replace(/\r\n/g, "\n");
const domain = (await fs.readFile(path.join(root, "protocol/domain.js"), "utf8")).replace(/\r\n/g, "\n");
const built = `// Generated by scripts/build-protocol.mjs. Do not edit.\n(function(root) {\nconst module = { exports: {} };\n${source}\nconst contracts = module.exports.createValidator(${JSON.stringify(schema)});\n${domain}\nroot.StepsembleProtocol = Object.freeze({ ...contracts, ...module.exports.createDomain(contracts) });\n})(globalThis);\n`;

// Generate declarations from the same schema: event type narrowing cannot drift
// from the actual wire payload. Only this repo's explicit vocabulary is supported.
const name = key => key === "event" ? "WireEvent" : key === "error" ? "ErrorEnvelope" : key[0].toUpperCase() + key.slice(1);
function type(node) {
  const parts = [];
  if (node.$ref) parts.push(name(node.$ref.slice(8)));
  if (Object.hasOwn(node, "const")) parts.push(JSON.stringify(node.const));
  else if (node.enum) parts.push(node.enum.map(item => JSON.stringify(item)).join(" | "));
  else if (node.type) {
    const kinds = (Array.isArray(node.type) ? node.type : [node.type]).map(kind => {
      if (kind === "integer" || kind === "number") return "number";
      if (kind === "array") return `Array<${node.items ? type(node.items) : "unknown"}>`;
      if (kind !== "object") return kind;
      const properties = Object.entries(node.properties || {}).map(([key, value]) => `${JSON.stringify(key)}${node.required?.includes(key) ? "" : "?"}: ${type(value)};`);
      if (node.additionalProperties !== false) properties.push("[key: string]: unknown;");
      return `{ ${properties.join(" ")} }`;
    });
    parts.push(kinds.join(" | "));
  }
  if (node.anyOf) parts.push(node.anyOf.map(child => `(${type(child)})`).join(" | "));
  return parts.length ? parts.map(part => `(${part})`).join(" & ") : "unknown";
}
const declarations = `// Generated by scripts/build-protocol.mjs. Do not edit.\ndeclare namespace StepsembleClient {\n${Object.entries(schema.$defs).map(([key, node]) => `  export type ${name(key)} = ${type(node)};`).join("\n")}\n}\n`;
for (const [relative, content] of [["public/modules/protocol-contracts.js", built], ["client/protocol-types.d.ts", declarations]]) {
  const target = path.join(root, relative);
  if (process.argv.includes("--check")) {
    if (content !== (await fs.readFile(target, "utf8")).replace(/\r\n/g, "\n")) throw new Error("Protocol artifact is stale; run npm run build:protocol");
  } else await fs.writeFile(target, content);
}
