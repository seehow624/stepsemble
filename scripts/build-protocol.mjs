#!/usr/bin/env node
// Mechanically embed the canonical schema and identical validator for browsers.
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = JSON.parse(await fs.readFile(path.join(root, "protocol/v1/schema.json"), "utf8"));
const source = (await fs.readFile(path.join(root, "protocol/validator.js"), "utf8")).replace(/\r\n/g, "\n");
const built = `// Generated by scripts/build-protocol.mjs. Do not edit.\n(function(root) {\nconst module = { exports: {} };\n${source}\nroot.StepsembleProtocol = module.exports.createValidator(${JSON.stringify(schema)});\n})(globalThis);\n`;
const target = path.join(root, "public/modules/protocol-contracts.js");
if (process.argv.includes("--check")) {
  if (built !== (await fs.readFile(target, "utf8")).replace(/\r\n/g, "\n")) throw new Error("Protocol artifact is stale; run npm run build:protocol");
} else await fs.writeFile(target, built);
