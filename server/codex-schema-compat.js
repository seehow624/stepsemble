"use strict";

// Decides whether a Codex app-server contract Stepsemble has not reviewed only
// adds to the latest one it has. Codex publishes a release every few days and
// most releases add methods, optional fields and enum values without touching
// what Stepsemble sends or reads; those are accepted without waiting for a
// Stepsemble release. Anything else (a removed field, a field that became
// required where Stepsemble sends it, a changed type, a removed notification
// or method Stepsemble uses) keeps the release out until it is reviewed.
//
// The comparison walks JSON Schema documents generated by
// `codex app-server generate-json-schema`. It is deliberately conservative:
// a change it cannot classify counts as breaking.

const SCHEMA_FILES = Object.freeze([...require("../protocol/native/codex/compatibility.json").schemaFiles]);

// Responses of methods Stepsemble calls that are not among the fingerprinted
// contract files. Their parameters are part of ClientRequest.json.
const EXTRA_READ_FILES = Object.freeze([
  "v2/ModelListResponse.json",
  "v2/ThreadForkResponse.json",
  "v2/ThreadSetNameResponse.json",
  "v2/ThreadGoalGetResponse.json",
  "v2/GetAccountRateLimitsResponse.json",
  "v2/TurnStartResponse.json",
  "v2/TurnInterruptResponse.json",
]);
const CONTRACT_FILES = Object.freeze([...SCHEMA_FILES, ...EXTRA_READ_FILES]);

// Every request method Stepsemble sends (server/codex-app-server-transport.js,
// codex-native-history-adapter.js, codex-thread-fork.js). Other methods may
// change or go away without affecting Stepsemble.
const USED_CLIENT_METHODS = Object.freeze([
  "initialize", "thread/start", "thread/resume", "thread/read", "thread/list", "thread/loaded/list",
  "thread/turns/list", "thread/items/list", "thread/goal/get", "thread/name/set", "thread/fork",
  "model/list", "turn/start", "turn/interrupt", "account/rateLimits/read",
]);

const IGNORED_KEYS = new Set(["description", "title", "examples", "default", "$schema", "$comment", "markdownDescription"]);
const MAX_PROBLEMS = 40;
// Raised whenever the comparison changes, so a verdict it made before is
// made again (server/codex-release-check.js keeps verdicts per release).
// 2: the same values written another way are compared shape by shape.
const COMPARISON_VERSION = 2;

// Documents Stepsemble writes are checked so that what it sends stays valid;
// the others so that what it reads keeps its shape.
function modeFor(file) {
  if (file === "ClientRequest.json") return "send";
  if (/^v[12]\//.test(file) && /Params\.json$/.test(file)) return "send";
  if (/ApprovalResponse\.json$/.test(file)) return "send";
  return "read";
}

function same(a, b) {
  if (a === b) return true;
  try { return JSON.stringify(a) === JSON.stringify(b); } catch { return false; }
}

// Equal text is only equal meaning when nothing in it points elsewhere: the
// definitions a reference names may have changed.
function settled(a, b) {
  if (a === b && (a === null || typeof a !== "object")) return true;
  let text;
  try { text = JSON.stringify(a); } catch { return false; }
  if (text.includes('"$ref"')) return false;
  try { return text === JSON.stringify(b); } catch { return false; }
}

function isObject(value) { return value !== null && typeof value === "object" && !Array.isArray(value); }

function typeSet(value) {
  if (value === undefined) return null;
  return new Set(Array.isArray(value) ? value : [value]);
}

function refName(ref) {
  const match = /^#\/(?:definitions|\$defs)\/(.+)$/.exec(String(ref || ""));
  return match ? match[1] : null;
}

// A stable name for a member of a oneOf/anyOf union, so a union that gained a
// member, or whose members gained optional fields, still lines up.
function variantKey(variant, index, enumIndex) {
  if (!isObject(variant)) return "value:" + JSON.stringify(variant);
  if (typeof variant.$ref === "string") return "ref:" + variant.$ref;
  const properties = isObject(variant.properties) ? variant.properties : null;
  if (properties) {
    const names = ["method", "type", "kind", "status", ...Object.keys(properties)];
    for (const name of names) {
      const property = properties[name];
      if (!isObject(property)) continue;
      if (Array.isArray(property.enum) && property.enum.length === 1) return "prop:" + name + "=" + JSON.stringify(property.enum[0]);
      if (Object.hasOwn(property, "const")) return "prop:" + name + "=" + JSON.stringify(property.const);
    }
  }
  if (Array.isArray(variant.enum)) return variant.enum.length === 1 ? "enum=" + JSON.stringify(variant.enum[0]) : "enum#" + enumIndex;
  if (typeof variant.title === "string" && variant.title) return "title:" + variant.title;
  if (!properties && (typeof variant.type === "string" || Array.isArray(variant.type))) return "type:" + JSON.stringify(variant.type);
  return "index:" + index;
}

function keyedVariants(list) {
  const keyed = new Map();
  let enums = 0;
  (Array.isArray(list) ? list : []).forEach((variant, index) => {
    const key = variantKey(variant, index, Array.isArray(variant?.enum) ? enums++ : enums);
    keyed.set(keyed.has(key) ? key + "@" + index : key, variant);
  });
  return keyed;
}

// How a schema lists the values it allows: through a reference, a union, a
// list of types, or as one shape.
function form(schema) {
  if (!isObject(schema)) return "value";
  const keys = Object.keys(schema).filter(key => !IGNORED_KEYS.has(key));
  if (keys.length === 1 && typeof schema.$ref === "string") return "ref";
  if (keys.length === 1 && (Array.isArray(schema.anyOf) || Array.isArray(schema.oneOf))) return "union";
  if (Array.isArray(schema.type) && schema.type.length > 1) return "types";
  return "single";
}

// The shapes a schema allows: one per member of a union and per type in a
// list of types, with references followed. Any other schema is one shape.
function shapes(schema, definitions, seen = new Set(), depth = 0) {
  const kind = form(schema);
  if (depth > 8 || kind === "single" || kind === "value") return [schema];
  if (kind === "types") return schema.type.map(type => ({ ...schema, type }));
  if (kind === "union") return (schema.anyOf || schema.oneOf).flatMap(member => shapes(member, definitions, seen, depth + 1));
  const name = refName(schema.$ref);
  if (!name || seen.has(name) || !isObject(definitions[name])) return [schema];
  return shapes(definitions[name], definitions, new Set([...seen, name]), depth + 1);
}

function createComparison(baseDocument, candidateDocument) {
  const baseDefinitions = baseDocument?.definitions || baseDocument?.$defs || {};
  const candidateDefinitions = candidateDocument?.definitions || candidateDocument?.$defs || {};
  const visited = new Set();
  const problems = [];
  let total = 0;
  const note = (path, reason) => { total += 1; if (problems.length < MAX_PROBLEMS) problems.push({ path: path || "(root)", reason }); };

  // A definition may be renamed between releases; the new name is compared
  // with what the old one described.
  function compareDefinition(name, mode, path, candidateName = name) {
    const key = name + ">" + candidateName + "|" + mode;
    if (visited.has(key)) return;
    visited.add(key);
    const base = baseDefinitions[name];
    const candidate = candidateDefinitions[candidateName];
    if (base === undefined) { note(path, "reference to an unknown definition " + name); return; }
    if (candidate === undefined) { note(name, candidateName === name ? "definition removed" : "reference to an unknown definition " + candidateName); return; }
    compare(base, candidate, name === candidateName ? name : name + ">" + candidateName, mode);
  }

  // Runs a comparison without recording what it finds; true when it finds
  // nothing. Used to ask whether a shape is still one of a union's members.
  function fits(base, candidate, mode, whole = false) {
    const savedTotal = total, savedProblems = problems.length, savedVisited = new Set(visited);
    compare(base, candidate, "", mode, whole);
    const clean = total === savedTotal;
    total = savedTotal;
    problems.length = savedProblems;
    visited.clear();
    for (const key of savedVisited) visited.add(key);
    return clean;
  }

  function compareProperties(base, candidate, path, mode) {
    const before = isObject(base.properties) ? base.properties : {};
    const after = isObject(candidate.properties) ? candidate.properties : {};
    for (const name of Object.keys(before)) {
      if (!Object.hasOwn(after, name)) note(path + "." + name, "field removed");
      else compare(before[name], after[name], path + "." + name, mode);
    }
    if (mode === "send") {
      const required = new Set(Array.isArray(candidate.required) ? candidate.required : []);
      for (const name of Object.keys(after)) {
        if (!Object.hasOwn(before, name) && required.has(name)) note(path + "." + name, "new required field");
      }
    }
  }

  function compareRequired(base, candidate, path, mode) {
    const before = new Set(Array.isArray(base.required) ? base.required : []);
    const after = new Set(Array.isArray(candidate.required) ? candidate.required : []);
    const beforeProperties = isObject(base.properties) ? base.properties : {};
    if (mode === "send") {
      // A field that is new and required is reported with the properties.
      for (const name of after) if (!before.has(name) && Object.hasOwn(beforeProperties, name)) note(path + "." + name, "field became required");
    } else {
      for (const name of before) if (!after.has(name)) note(path + "." + name, "field may now be missing");
    }
  }

  function compareVariants(base, candidate, path, mode) {
    const before = keyedVariants(base);
    const after = keyedVariants(candidate);
    for (const [key, variant] of before) {
      if (!after.has(key)) note(path + "[" + key + "]", "union member removed");
      else compare(variant, after.get(key), path + "[" + key + "]", mode);
    }
  }

  function compareType(base, candidate, path, mode) {
    const before = typeSet(base.type), after = typeSet(candidate.type);
    if (!before && after) { if (mode === "send") note(path, "type restricted"); return; }
    if (before && !after) { if (mode === "read") note(path, "type loosened"); return; }
    // Sending needs every type Stepsemble may send to stay accepted; reading
    // needs no type Stepsemble does not expect.
    const [smaller, larger] = mode === "send" ? [before, after] : [after, before];
    for (const type of smaller) if (!larger.has(type)) { note(path, "type changed"); return; }
  }

  function compareEnum(base, candidate, path, mode) {
    const hasBefore = Array.isArray(base.enum), hasAfter = Array.isArray(candidate.enum);
    if (!hasBefore && hasAfter) { if (mode === "send") note(path, "values restricted"); return; }
    if (hasBefore && !hasAfter) { if (mode === "read") note(path, "values loosened"); return; }
    const after = new Set(candidate.enum.map(value => JSON.stringify(value)));
    for (const value of base.enum) if (!after.has(JSON.stringify(value))) note(path, "value removed: " + JSON.stringify(value));
  }

  function compare(base, candidate, path, mode, whole = false) {
    if (settled(base, candidate)) return;
    if (!isObject(base) || !isObject(candidate)) { note(path, "changed"); return; }
    // The same values may be written another way: a list of types as a
    // union, or a union moved behind a reference (Codex 0.159.0's
    // thread/items/list cursor). Then each shape is compared on its own:
    // every shape Stepsemble may send must still be accepted by one, and
    // every shape it may read must be one it knew.
    if (!whole && form(base) !== form(candidate)) {
      const before = shapes(base, baseDefinitions), after = shapes(candidate, candidateDefinitions);
      if (before.length > 1 || after.length > 1) {
        const covered = mode === "send"
          ? before.every(shape => after.some(member => fits(shape, member, mode, true)))
          : after.every(shape => before.some(member => fits(member, shape, mode, true)));
        if (covered) return;
      }
    }
    // A shape that became a union still fits when it is one of the members:
    // what Stepsemble sends is still accepted. What it reads may now take
    // other shapes, so that stays a change.
    const union = !base.oneOf && !base.anyOf ? candidate.oneOf || candidate.anyOf : null;
    if (Array.isArray(union) && mode === "send") {
      const { oneOf, anyOf, ...rest } = candidate;
      const remainder = Object.keys(rest).filter(key => !IGNORED_KEYS.has(key));
      if (!remainder.length && union.some(member => fits(base, member, mode))) return;
    }
    if (base.$ref !== undefined || candidate.$ref !== undefined) {
      if (base.$ref === undefined || candidate.$ref === undefined) { note(path, "reference changed"); return; }
      const name = refName(base.$ref), candidateName = refName(candidate.$ref);
      if (!name || !candidateName) { note(path, "unsupported reference"); return; }
      compareDefinition(name, mode, path, candidateName);
    }
    const keys = new Set([...Object.keys(base), ...Object.keys(candidate)]);
    for (const key of keys) {
      if (IGNORED_KEYS.has(key) || key === "$ref" || key === "definitions" || key === "$defs") continue;
      const inBase = Object.hasOwn(base, key), inCandidate = Object.hasOwn(candidate, key);
      if (inBase && inCandidate && settled(base[key], candidate[key])) continue;
      if (key === "properties") { compareProperties(base, candidate, path, mode); continue; }
      if (key === "required") { compareRequired(base, candidate, path, mode); continue; }
      if (key === "type") { compareType(base, candidate, path, mode); continue; }
      if (key === "enum") { compareEnum(base, candidate, path, mode); continue; }
      if (key === "oneOf" || key === "anyOf") {
        if (!inBase) { if (mode === "send") note(path + "." + key, "values restricted"); continue; }
        if (!inCandidate) { note(path + "." + key, "union replaced"); continue; }
        compareVariants(base[key], candidate[key], path + "." + key, mode);
        continue;
      }
      if (key === "allOf" || key === "items" && (Array.isArray(base.items) || Array.isArray(candidate.items))) {
        const before = base[key], after = candidate[key];
        if (!Array.isArray(before) || !Array.isArray(after) || before.length !== after.length) { note(path + "." + key, "changed"); continue; }
        before.forEach((item, index) => compare(item, after[index], path + "." + key + "[" + index + "]", mode));
        continue;
      }
      if ((key === "items" || key === "additionalProperties" || key === "not") && isObject(base[key]) && isObject(candidate[key])) {
        compare(base[key], candidate[key], path + "." + key, mode);
        continue;
      }
      // Any other keyword: new ones may only narrow what is read (harmless)
      // and removed ones may only widen what Stepsemble sends (harmless).
      if (!inBase) { if (mode === "send") note(path + "." + key, "new constraint " + key); continue; }
      if (!inCandidate) { if (mode === "read") note(path + "." + key, "constraint " + key + " removed"); continue; }
      note(path + "." + key, key + " changed");
    }
  }

  function root(mode) {
    const strip = document => { const { definitions, $defs, ...rest } = document || {}; return rest; };
    compare(strip(baseDocument), strip(candidateDocument), "", mode);
  }

  // ClientRequest lists every request method; only the ones Stepsemble sends
  // have to stay the same.
  function clientRequests(methods) {
    const wanted = new Set(methods);
    const pick = document => new Map((Array.isArray(document?.oneOf) ? document.oneOf : [])
      .map(variant => [variant?.properties?.method?.enum?.length === 1 ? variant.properties.method.enum[0] : null, variant])
      .filter(([method]) => typeof method === "string" && wanted.has(method)));
    const before = pick(baseDocument), after = pick(candidateDocument);
    for (const [method, variant] of before) {
      if (!after.has(method)) note(method, "request method removed");
      else compare(variant, after.get(method), method, "send");
    }
  }

  return { compare, root, clientRequests, problems, total: () => total };
}

// baseline and candidate map each contract file name to its parsed document.
function compareCodexContracts(baseline, candidate, { files = CONTRACT_FILES, usedMethods = USED_CLIENT_METHODS } = {}) {
  const breaking = [];
  let breakingCount = 0;
  for (const file of files) {
    const base = baseline?.[file], next = candidate?.[file];
    if (!isObject(base)) { breaking.push({ file, path: "(file)", reason: "no reviewed baseline" }); breakingCount += 1; continue; }
    if (!isObject(next)) { breaking.push({ file, path: "(file)", reason: "file missing" }); breakingCount += 1; continue; }
    const comparison = createComparison(base, next);
    if (file === "ClientRequest.json") comparison.clientRequests(usedMethods);
    else comparison.root(modeFor(file));
    breakingCount += comparison.total();
    for (const problem of comparison.problems) if (breaking.length < MAX_PROBLEMS) breaking.push({ file, ...problem });
  }
  return Object.freeze({ compatible: breakingCount === 0, breakingCount, breaking: Object.freeze(breaking) });
}

module.exports = { CONTRACT_FILES, EXTRA_READ_FILES, USED_CLIENT_METHODS, COMPARISON_VERSION, compareCodexContracts, modeFor };
