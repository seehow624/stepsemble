  function normalizeLocale(value) {
    if (tables[value]) return value;
    const key = String(value || "").toLowerCase();
    if (/^zh-(tw|hk|mo|hant)/.test(key)) return "zh-Hant";
    if (key.startsWith("zh")) return "zh-Hans";
    if (key.startsWith("pt")) return "pt-BR";
    return tables[key.split("-")[0]] ? key.split("-")[0] : "en";
  }
